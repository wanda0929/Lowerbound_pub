"""Generate and check the small terminal payload for the fixed Gram archive.
The large occupation/interface matrices already live in their pinned modules.
"""
import argparse
import gzip
import hashlib
import json
from pathlib import Path
from flint import fmpq as Q
from bind_allocations import load_checker
from bind_certificates import LOWER, RAW, scalar, need


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('checkout',type=Path)
    p.add_argument('--output',type=Path)
    p.add_argument('--lean-dump',type=Path)
    p.add_argument('--report',type=Path)
    a=p.parse_args()
    load_checker(a.checkout)
    raw=gzip.decompress(b''.join((a.checkout/LOWER/f'certificate.json.gz.part-{i:02}').read_bytes() for i in range(2)))
    need(hashlib.sha256(raw).hexdigest()==RAW,'original source hash')
    cert=json.loads(raw)
    arrays=[]
    expected=[]
    for j,cell in enumerate(cert['terminal_grams_by_cell']):
        for t,m in enumerate(cell):
            n=8-t
            need(len(m)==n and all(len(r)==n for r in m),'terminal shape')
            values=[scalar(c) for row in m for c in row]
            need(all(values[i*n+k]==values[k*n+i] for i in range(n) for k in range(n)),'terminal symmetry')
            arrays.append(' '.join(f'{x},{y}' for x,y in values))
            expected.append(f'T {j} {t} '+ ' '.join(f'{x.numerator}/{x.denominator},{y.numerator}/{y.denominator}' for x,y in values))
    if a.output:
        a.output.write_text('-- Generated by bind_archive.py; exact original terminal matrices.\n'
            'import LowerBoundCZ.AllocationCodec\nnamespace LowerBoundCZ.ArchiveData\n'
            'def terminal : Array String := #[\n  '+',\n  '.join(json.dumps(x) for x in arrays)+
            '\n]\nend LowerBoundCZ.ArchiveData\n')
    if a.lean_dump:
        lines=a.lean_dump.read_text().splitlines()
        terminal=[s for s in lines if s.startswith('T ')]
        need(terminal==expected,'all decoded terminal entries')
        # The audit also exports each fixed raw block's used-column map and
        # checks all finite RawBlock.Valid conditions before emitting it.
        blocks=[s for s in lines if s.startswith('B ')]
        need(len(blocks)==4216,'all fixed nonterminal blocks')
        binding=json.loads(Path('certificate-bindings.json').read_text())
        seen=set()
        for line in blocks:
            _,kind,cell,block,*used=line.split()
            cell,block=int(cell),int(block)
            need((kind,cell,block) not in seen,'duplicate archive block')
            seen.add((kind,cell,block))
            layout=binding['lean_gram_bridge']['occupation' if kind=='O' else 'interface'][block]
            need(list(map(int,used))==layout['source_basis_indices'],'archive used-column correspondence')
        need(seen=={('O',j,b) for j in range(5) for b in range(736)} |
                    {('I',j,b) for j in range(4) for b in range(134)},'complete archive block set')
        vs=[s.split() for s in lines if s.startswith('V ')]
        need(len(vs)==5,'five terminal restrictions')
        for j,row in enumerate(vs):
            need(row[:2]==['V',str(j)] and len(row)==17,'terminal restriction shape')
            target=[tuple(map(Q,s.split(','))) for s in row[2:]]
            power=[[Q(0),Q(0)] for _ in range(15)]
            for t,m in enumerate(cert['terminal_grams_by_cell'][j]):
                for i,r in enumerate(m):
                    for k,s in enumerate(r):
                        for z,value in enumerate(scalar(s)):
                            c=Q(str(value))
                            if t==0:
                                power[i+k][z]+=c
                            else:
                                power[i+k+1][z]+=c
                                power[i+k+2][z]-=c
            need(list(map(tuple,power))==target,'terminalRestriction(V)+offset equals terminal Gram')
        report=dict(status='PASS',source_sha256=RAW,nonterminal_blocks=4216,terminal_matrices=10,
                    terminal_entries=565,terminal_coefficient_identities=75,
                    decoded_sha256=hashlib.sha256(a.lean_dump.read_bytes()).hexdigest(),
                    checker_sha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest())
        if a.report:
            a.report.write_text(json.dumps(report,indent=2)+'\n')
        print('PASS: all 4216 fixed block maps and all 565 terminal entries match the original archive')


if __name__=='__main__':
    main()
