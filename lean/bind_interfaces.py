"""Bind the four pinned interface Grams, combined allocations and W64 credits.

Replays the original interface matrix checker and the reachable-box checker.
This exports data and external validation, not a kernel proof of finite checks.
"""
import argparse
from fractions import Fraction as F
import gzip
import hashlib
import importlib.util
import json
from pathlib import Path

from bind_allocations import load_checker
from bind_certificates import LOWER, RAW, scalar
from bind_slack import need

CROSS = "98560cc0bd55714dfb74814e377caac64cb4c736652e33868925da7b25703fd7"
BASES = "4d93e3093e555e837f72e218118cd43ada2f71b584fd48a7a525a5f73324a495"


def load(root):
    checker = load_checker(root)
    v, _, occ, _, old = checker.inputs(root / "sdp")
    directory = root / "sdp/verification_results"
    raw = (directory / "slack-campaign-2935/crossing.json").read_bytes()
    # Bound to the final combined certificate's crossing input hash.
    final = json.loads((directory / "slack-campaign-2935/certificate.json").read_text())
    need(hashlib.sha256(raw).hexdigest() == final["crossing_sha256"], "reachable crossing hash")
    cert = json.loads(raw)
    checker.crossing(v, old, occ, cert)
    spec = importlib.util.spec_from_file_location("interface_verifier", directory / "interface-population/verify.py")
    verifier = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(verifier)
    from flint import ctx
    ctx.prec = 384
    source_raw = gzip.decompress(b"".join((root / LOWER / f"certificate.json.gz.part-{i:02}").read_bytes()
                                        for i in range(2)))
    need(hashlib.sha256(source_raw).hexdigest() == RAW, "original source hash")
    source = json.loads(source_raw)
    basis_raw = (directory / "population-refinement/certified/interface-bases.json").read_bytes()
    need(hashlib.sha256(basis_raw).hexdigest() == BASES, "native basis hash")
    bases = json.loads(basis_raw)
    base_raw = (directory / "population-refinement/certified/subdivision-certificate.json").read_bytes()
    need(hashlib.sha256(base_raw).hexdigest() == verifier.BASE, "interface predecessor hash")
    report = verifier.verify(old, source, bases, json.loads(base_raw))
    report["self_tests"] = verifier.tests(json.loads(base_raw), old)
    need(cert["grid"] == cert["barrier_series_order"] == 64, "pinned grid and barrier order")
    return source, bases, old, cert, hashlib.sha256(raw).hexdigest(), report, checker, v


def export(root, destination, dump=None):
    source, bases, old, cert, reach_hash, report, checker, v = load(root)
    matrices = source["interface_grams_by_knot"]
    need([len(x) for x in matrices] == [134]*4 and len(bases) == 134, "all original interface blocks")
    lines = ["-- Generated by bind_interfaces.py; do not edit.",
             "import LowerBoundCZ.AllocationCodec", "namespace LowerBoundCZ.InterfaceData",
             "open AllocationCodec", "set_option maxRecDepth 10000", "set_option maxHeartbeats 0"]
    expected = []
    def put(tag, *values):
        expected.append(" ".join([tag, *map(str, values)]))
    def qstr(q):
        q = F(q)
        return f"{q.numerator}/{q.denominator}"
    for j in range(4):
        diag = [[F(0)]*len(q) for q in matrices[j]]
        power = [F(0)]*64
        from math import comb
        for rid, w in old["crossings"][j]["allocations"]:
            rec = old["records"][rid]
            need(rec["knot"] == j, "allocation knot")
            rate = F(w)*F(rec["gamma"])
            diag[rec["block"]][rec["row"]] += rate
            g,r,h,s = rec["population_exponents"]
            for a in range(g+1):
                for b in range(h+1):
                    power[8*(r+a)+s+b] += rate*(-1)**(a+b)*comb(g,a)*comb(h,b)
        for b, matrix in enumerate(matrices[j]):
            n = len(matrix)
            need(n == len(bases[b]) and all(len(row) == n for row in matrix), "source shape")
            q = [[scalar(x) if "sqrt" in x else (F(x),F(0)) for x in row] for row in matrix]
            need(all(q[a][c] == q[c][a] for a in range(n) for c in range(n)), "source symmetry")
            codes=[]
            for m in bases[b]:
                need(m["cost_power"] == 0 and len(m["holo"]) == len(m["anti"]) == 4, "state-only column")
                powers=[0,0,0]+[e for pair in zip(m["holo"],m["anti"]) for e in pair]
                need(all(0 <= e < 16 for e in powers), "power encoding")
                codes.append(2*sum(e*16**i for i,e in enumerate(powers)))
            upper=" ".join(f"{a},{c}" for i in range(n) for a,c in q[i][i:])
            rows="|".join(f"{i}:1" for i in range(n))
            index=j*134+b
            lines.append(f'def source{index} : EncodedSource := ⟨{n}, 0, {json.dumps(" ".join(map(str,codes)))}, {json.dumps(rows)}, {json.dumps(upper)}⟩')
            lines.append(f'def diagonal{index} : String := {json.dumps(" ".join(map(str,diag[b])))}')
            put("S",index,n)
            put("B",index,*codes)
            put("Q",index,*(f"{qstr(a)},{qstr(c)}" for row in q for a,c in row))
            put("D",index,*(qstr(x) for x in diag[b]))
        lines.append(f'def power{j} : String := {json.dumps(" ".join(map(str,power)))}')
        lines.append(f'def credit{j} : String := {json.dumps(cert["crossings"][j]["bound"])}')
        put("P",j,*(qstr(x) for x in power))
        put("K",j,qstr(cert["crossings"][j]["bound"]))
    series = checker.barrier(64)
    energies = [F(i,64)**3*sum((c*F(i,64)**k for k,c in enumerate(series)),F(0))**2
                for i in range(64)]
    put("E",*(qstr(x) for x in energies))
    from flint import fmpq as Q, fmpq_mat as Mat
    for j in range(4):
        C = v.U*v.KNOTS[j+1]
        radius = min(C,F(733,250)-C)
        bits=[]
        for x in range(64):
            for y in range(64):
                A,D,T=8*energies[x],energies[y],72*radius**2
                bits.append('1' if A+D>T or (T-A-D)**2<4*A*D else '0')
        need(bits.count('0')==cert['crossings'][j]['retained_boxes'],"classification count")
        put("X",j,"".join(bits))
        # Use the independent checker's tensor path, not the Lean formula.
        power=[Q(0)]*64
        for rid,w in old['crossings'][j]['allocations']:
            r=old['records'][rid]
            g,a,h,b=r['population_exponents']
            for u in range(g+1):
                for z in range(h+1):
                    power[8*(a+u)+b+z]+=Q(w)*Q(r['gamma'])*(-1)**(u+z)*comb(g,u)*comb(h,z)
        for x,y in ((0,0),(17,42),(63,63)):
            values=Mat([power])*v.popmap(7,x,y,64)[0]
            for a,b in ((0,7),(3,5),(7,0)):
                put("T",j,x,y,a,b,qstr(F(str(values[0,8*a+b]))-F(cert['crossings'][j]['bound'])))
    for name, prefix, n, ty in (("sources","source",536,"EncodedSource"),
                               ("diagonals","diagonal",536,"String"),
                               ("powers","power",4,"String"),("credits","credit",4,"String")):
        lines.append(f'def {name} : Array {ty} := #['+", ".join(f"{prefix}{i}" for i in range(n))+"]")
    lines.append("end LowerBoundCZ.InterfaceData")
    destination.write_text("\n".join(lines)+"\n")
    manifest={"source":RAW,"basis":BASES,"allocation":CROSS,"reachable":reach_hash,
              "lean_sha256":hashlib.sha256(destination.read_bytes()).hexdigest(),"external_checks":report,
              "retained_boxes":[x["retained_boxes"] for x in cert["crossings"]],
              "discarded_boxes":[x["discarded_boxes"] for x in cert["crossings"]]}
    destination.with_suffix(".json").write_text(json.dumps(manifest,indent=2)+"\n")
    if dump:
        actual=dump.read_text().splitlines()
        need(actual==expected,"Lean-decoded matrices, columns, diagonals, powers or credits differ")
        print("PASS: 536 blocks, 247744 full matrix entries, columns, combined diagonals, powers, credits, 16384 box classifications and 36 tensor samples match")
    print(json.dumps({"blocks":536,"retained":manifest["retained_boxes"],"discarded":manifest["discarded_boxes"]}))


if __name__ == "__main__":
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument("checkout",type=Path)
    p.add_argument("--output",type=Path,default=Path("LowerBoundCZ/InterfaceData.lean"))
    p.add_argument("--lean-dump",type=Path)
    a=p.parse_args()
    export(a.checkout.resolve(),a.output,a.lean_dump)
