"""Bootstrap from the first 319 final profiles, never from an unproved prefix.

Export a finite terminal polynomial identity. This checks no PSD matrices and
does not treat any predecessor's PASS or bound label as a theorem.
"""
import argparse
from fractions import Fraction as F
import gzip
import hashlib
import json
from math import comb
from pathlib import Path

from bind_certificates import LOWER, RAW, basis, scalar, qlean
from bind_profiles import collect, power_coefficients
from bind_slack import HASHES, need


def data(root, final=False):
    raw = gzip.decompress(b"".join((root / LOWER / f"certificate.json.gz.part-{i:02}").read_bytes()
                                  for i in range(2)))
    need(hashlib.sha256(raw).hexdigest() == RAW, "original potential hash")
    source = json.loads(raw)
    p = collect(root)
    profiles = p["profiles"]
    L, B, U = F(5861, 2000), F(profiles[320]["right"]), F(source["exposure_upper"])
    need(F(profiles[318]["right"]) < L < B < F(733, 250), "noncircular prefix")
    final_raw = (root / "sdp/verification_results/slack-campaign-2935/certificate.json").read_bytes()
    need(hashlib.sha256(final_raw).hexdigest() == HASHES["certificate.json"], "final hash")
    crossing_raw = (root / "sdp/verification_results/slack-campaign-2935/crossing.json").read_bytes()
    need(hashlib.sha256(crossing_raw).hexdigest() == json.loads(final_raw)["crossing_sha256"], "crossing hash")
    interfaces = [F(x["bound"]) for x in json.loads(crossing_raw)["crossings"]]
    need(len(interfaces) == 4, "interface count")
    K = sum((F(x["credit"]) for x in profiles[:319]), F(0))
    if final:
        raw_endpoint = (root / "sdp/verification_results/slack-campaign-2935/dark/endpoint.json").read_bytes()
        need(hashlib.sha256(raw_endpoint).hexdigest() == HASHES["dark/endpoint.json"], "final endpoint hash")
        endpoint = json.loads(raw_endpoint)
        B = F(endpoint["bound"])
        K = sum((F(x["credit"]) for x in profiles), F(0))
    terminal = [[F(0), F(0)] for _ in range(14)]
    tests = basis(4, 13, True)[(0, 0)]
    row = source["liouville_multipliers_by_cell"][4]
    need(len(tests) == len(row) == 776, "potential size")
    for (d, anti, holo), coefficient in zip(tests, row):
        weight = 0 if anti[1]+anti[3]+holo[1]+holo[3] else (-1)**(anti[2]+holo[2])
        for component, value in enumerate(scalar(coefficient)):
            terminal[d][component] -= value*weight
    a, b = 36*L/U-35, 36*(B-L)/U
    power = [[sum((terminal[d][c]*comb(d,k)*a**(d-k)*b**k for d in range(k,14)), F(0))
              for c in range(2)] for k in range(14)]
    offset = scalar(source["normalization"])
    power[0][0] += offset[0]+L+K+sum(interfaces)-B
    power[0][1] += offset[1]
    need(all(v[1] == 0 for v in power), "sqrt(2) coefficient cancellation")
    beta = [sum((power[k][0]*F(comb(i,k),comb(13,k)) for k in range(i+1)), F(0)) for i in range(14)]
    need(min(beta) > 0, "bootstrap Bernstein positivity")
    need(power_coefficients(beta) == [v[0] for v in power], "all polynomial coefficients")
    if final:
        need(beta == list(map(F, endpoint["endpoint_bernstein"])), "original final endpoint identity")
    return terminal, beta, K, interfaces


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("checkout", type=Path)
    ap.add_argument("--output", type=Path)
    ap.add_argument("--lean-dump", type=Path)
    ap.add_argument("--final", action="store_true", help="check the final 321-profile endpoint, without exporting bootstrap data")
    args = ap.parse_args()
    need(not (args.final and args.output), "final mode does not export PrefixData")
    terminal, beta, K, interfaces = data(args.checkout, args.final)
    if args.output:
        lines = ["-- Generated by bind_prefix.py; do not edit.", "import Mathlib.Data.Rat.Defs",
                 "namespace LowerBoundCZ.PrefixData", "def beta (i : Fin 14) : ℚ := match i.val with"]
        lines += [f"  | {i if i < 13 else '_'} => {qlean(q)}" for i,q in enumerate(beta)]
        lines += ["end LowerBoundCZ.PrefixData", ""]
        args.output.write_text("\n".join(lines))
    if args.lean_dump:
        expected = [[str(x) for x in pair] for pair in terminal]
        expected += [[str(q)] for q in beta] + [[str(K)]] + [[str(q)] for q in interfaces]
        actual = [[str(F(x)) for x in line.split()] for line in args.lean_dump.read_text().splitlines()]
        need(actual == expected, "Lean/source terminal, Bernstein, prefix credit and interfaces")
    scope = "321 final profiles" if args.final else "319 already-reached profiles"
    print(f"PASS: {scope}; 14 exact positive endpoint coefficients; minimum {float(min(beta)):.12g}")


if __name__ == "__main__":
    main()
