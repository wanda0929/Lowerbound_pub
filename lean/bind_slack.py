"""Export the pinned final slack endpoint, not a physical-bound verifier.

The full reachability/profile proof is a separate obligation. This exporter
does not interpret a checker PASS or a bound label as a Lean theorem.
"""
import argparse
from fractions import Fraction
import hashlib
import json
from pathlib import Path
import subprocess

REV = "139dfc0aeb39fbc09d9352a3cbfcd603cb6612e2"
DIRECTORY = "sdp/verification_results/slack-campaign-2935"
HASHES = {
    "dark/endpoint.json": "2233ea50ec35a98bdf67ef58421bc2aba5c4b04c8d885083b6b96225f14758e6",
    "dark/profiles.json": "c0914234454ad76d951364d7ef43d54ee1dc40fd053764be19a0188f489adac9",
    "certificate.json": "106e5d046b22c8456135c40f9a77ee01f346a69c694983d917b69ab8675d830c",
}


def need(condition, message):
    if not condition:
        raise ValueError(message)


def rat(value):
    q = Fraction(value)
    return f"({q.numerator}/{q.denominator} : ℚ)"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("checkout", type=Path)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    revision = subprocess.check_output(
        ["git", "-C", str(args.checkout), "rev-parse", "HEAD"], text=True).strip()
    need(revision == REV, "publication revision")
    data = {}
    for name, expected in HASHES.items():
        raw = (args.checkout / DIRECTORY / name).read_bytes()
        need(hashlib.sha256(raw).hexdigest() == expected, f"hash: {name}")
        data[name] = json.loads(raw)
    endpoint, parent = data["dark/endpoint.json"], data["certificate.json"]
    need(Fraction(endpoint["bound"]) == Fraction("2.931287735220"), "target")
    need(endpoint["profiles_sha256"] == HASHES["dark/profiles.json"], "profile binding")
    need(Fraction(endpoint["gain"]) == Fraction(data["dark/profiles.json"]["exact_integrated_gain"]),
         "gain binding")
    output = ["-- Generated by bind_slack.py; do not edit.",
              "import Mathlib.Data.Rat.Defs", "import Mathlib.Data.Fin.VecNotation",
              "namespace LowerBoundCZ.SlackData", ""]
    for name, value in (("bound", endpoint["bound"]), ("parentBound", parent["bound"]),
                        ("gain", endpoint["gain"])):
        output.append(f"def {name} : ℚ := {rat(value)}")
    for name, values in (("endpoint", endpoint["endpoint_bernstein"]),
                         ("parentEndpoint", parent["endpoint_bernstein"])):
        need(len(values) == 14, f"degree: {name}")
        output.append(f"def {name} (i : Fin 14) : ℚ := match i.val with")
        output.extend(f"  | {i} => {rat(value)}" for i, value in enumerate(values[:-1]))
        output.append(f"  | _ => {rat(values[-1])}")
    output += ["", "end LowerBoundCZ.SlackData", ""]
    args.output.write_text("\n".join(output))
    print("Pinned endpoint exported; no physical lower-bound assertion made.")


if __name__ == "__main__":
    main()
