"""Export fixed population-box lookup indices, independently of Lean proofs."""
import argparse
from fractions import Fraction as F
import json
from pathlib import Path
from bind_profiles import collect
from bind_regions import module
from bind_slack import need


def tables(root):
    profiles = collect(root)["profiles"]
    directory = root / "sdp/verification_results"
    reach = module(directory / "reachability-slack/verify.py", "cover_reach")
    dark = module(directory / "slack-campaign-2935/dark/verify.py", "cover_dark")
    h, _ = reach.barrier_coefficients()
    grids, kinds, rows = [], [], []
    next_region = 0
    for i, p in enumerate(profiles):
        n = p["grid"]
        kind = {"reachable": 1, "dark": 2}.get(p["owner"], 0)
        grids.append(n); kinds.append(kind); row = []
        radius = min(F(p["right"]), F(733,250)-F(p["left"]))
        for x in range(n):
            for y in range(n):
                excluded = ((kind == 1 and reach.excluded(x,y,n,radius,h)) or
                            (kind == 2 and dark.excluded(x,y,n,radius)))
                if excluded:
                    row.append(0)
                elif p["owner"] == "allocation":
                    row.append(1+(i-176)*64+x*8+y)
                else:
                    row.append(1+1024+next_region); next_region += 1
        rows.append(row)
    need(next_region == 9728, "regional lookup count")
    return grids, kinds, rows


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("checkout", type=Path)
    parser.add_argument("--output", type=Path)
    parser.add_argument("--lean-dump", type=Path)
    args = parser.parse_args()
    grids, kinds, rows = tables(args.checkout)
    def array(xs):
        return "#["+", ".join(xs)+"]"
    need(args.output is not None or args.lean_dump is not None, "choose output or lean-dump")
    if args.output:
        args.output.write_text("-- Generated by bind_coverage.py; do not edit.\n"
        "import LowerBoundCZ.AllocationCodec\nnamespace LowerBoundCZ.CoverageData\n"
        "set_option maxRecDepth 10000\n"
        "def grids : Array Nat := "+array(list(map(str,grids)))+"\n"
        "def kinds : Array Nat := "+array(list(map(str,kinds)))+"\n"
        "def boxes : Array String := "+array([json.dumps(" ".join(map(str,r))) for r in rows])+"\n"
            "end LowerBoundCZ.CoverageData\n")
    if args.lean_dump:
        compare(grids, kinds, rows, args.lean_dump)
    print("PASS: 321 fixed grids; 10752 retained and 12336 excluded box entries")


def compare(grids, kinds, rows, path):
    with path.open() as stream:
        for i, (n, kind, row) in enumerate(zip(grids,kinds,rows)):
            for x in range(n):
                for y in range(n):
                    c = row[x*n+y]
                    expected = f"{i} {n} {kind} {x} {y} {c} {str(c == 0).lower()}"
                    need(stream.readline().strip() == expected, f"lookup/classification mismatch {i}/{x}/{y}")
        need(stream.read() == "", "extra coverage entries")


if __name__ == "__main__":
    main()
